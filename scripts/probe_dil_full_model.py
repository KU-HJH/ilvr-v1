def sha256(path):
    digest = hashlib.sha256()
    with Path(path).open("rb") as stream:
        for chunk in iter(lambda: stream.read(8 * 1024 * 1024), b""):
            digest.update(chunk)
    return digest.hexdigest()


def json_bytes(value):
    return json.dumps(value, sort_keys=True, separators=(",", ":"), allow_nan=False).encode()


def read_json(path):
    def unique(pairs):
        result = {}
        for key, value in pairs:
            if key in result:
                raise ValueError(f"duplicate JSON field {key}")
            result[key] = value
        return result
    return json.loads(Path(path).read_text(), object_pairs_hook=unique)


def contained(path, root):
    path, root = Path(path), Path(root)
    if not path.is_absolute() or ".." in path.parts or not path.resolve().is_relative_to(root.resolve()):
        raise ValueError(f"path must be inside {root}: {path}")
    return path


def tensor_directory(repository, run_id):
    if not re.fullmatch(r"[a-z0-9][a-z0-9-]{2,127}", run_id):
        raise ValueError("invalid probe run_id")
    root = Path(repository) / "checkpoints"
