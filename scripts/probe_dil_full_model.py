@contextmanager
def observe_call(owner, name, observer):
    original = getattr(owner, name)
    def call(*args, **kwargs):
        result = original(*args, **kwargs)
        observer(args, kwargs, result)
        return result
    setattr(owner, name, call)
    try:
        yield
    finally:
        setattr(owner, name, original)


def tensor_record(tensor):
    tensor = tensor.detach().contiguous().cpu()
    return {"shape": list(tensor.shape), "dtype": str(tensor.dtype),
            "sha256": hashlib.sha256(tensor.view(-1).view(__import__("torch").uint8).numpy().tobytes()).hexdigest()}


def state_record(model):
    return {name: {**tensor_record(value), "trainable": bool(value.requires_grad)}
            for name, value in [*model.named_parameters(), *model.named_buffers()]}


def snapshot(value):
    import torch
    from dataclasses import fields, is_dataclass
    if isinstance(value, torch.Tensor):
        return tensor_record(value)
    if is_dataclass(value):
        return {field.name: snapshot(getattr(value, field.name)) for field in fields(value)}
    if isinstance(value, dict):
        return {str(key): snapshot(item) for key, item in value.items()}
    if isinstance(value, (tuple, list)):
        return [snapshot(item) for item in value]
    if value is None or isinstance(value, (str, bool, int, float)):
        return value
    raise ValueError(f"unsupported collator metadata {type(value)}")


def compare_gradients(expected, actual):
    import torch
    result = {"pass": True, "comparator": COMPARATOR, "parameters": {}, "identity_mismatches": []}
    if set(expected) != set(actual):
        result["identity_mismatches"].append({"names_missing": sorted(set(expected)-set(actual)), "names_extra": sorted(set(actual)-set(expected))})
    squared = reference_squared = 0.
    maximum = 0.
    for name in sorted(set(expected) & set(actual)):
        e, a = expected[name], actual[name]
        if e is None or a is None:
            match = e is None and a is None
            result["parameters"][name] = {"pass": match, "expected_none": e is None, "actual_none": a is None}
        elif e.shape != a.shape or e.dtype != a.dtype:
            match = False
            result["parameters"][name] = {"pass": False, "identity": "shape/dtype mismatch"}
        else:
            e, a = e.detach().cpu().double(), a.detach().cpu().double()
            finite = bool(torch.isfinite(e).all() and torch.isfinite(a).all())
            difference = (a-e).abs()
            failed = (~torch.isfinite(difference)) | (difference > (COMPARATOR["atol"]+COMPARATOR["rtol"]*e.abs()))
            match = finite and not bool(failed.any())
            error2, norm2 = float(difference.square().sum()), float(e.square().sum())
            maxabs = float(difference.max()) if difference.numel() else 0.
            squared += error2
            reference_squared += norm2
            maximum = max(maximum, maxabs)
            result["parameters"][name] = {"pass": match, "finite": finite, "failed_coordinates": int(failed.sum()),
                                           "max_abs_error": maxabs if finite else None, "l2_error": math.sqrt(error2) if finite else None,
                                           "relative_l2": math.sqrt(error2/norm2) if finite and norm2 else (0. if finite and not error2 else None)}
        result["pass"] &= match
    result["pass"] &= not result["identity_mismatches"]
    result.update(max_abs_error=maximum if math.isfinite(maximum) else None,
                  l2_error=math.sqrt(squared) if math.isfinite(squared) else None,
                  relative_l2=math.sqrt(squared/reference_squared) if reference_squared and math.isfinite(squared) else (0. if squared == 0 else None))
    return result


def differentiate(trainer, model, batch, scope, phase=None):
    import torch
    named = [(name, parameter) for name, parameter in model.named_parameters() if parameter.requires_grad]
    if not named:
        raise ValueError("no trainable parameters")
    with scope:
        loss = trainer.compute_loss(model, batch, return_outputs=False)
        if phase:
            phase("post_forward")
        gradients = torch.autograd.grad(loss, [parameter for _, parameter in named], allow_unused=True)
        if phase:
            phase("post_backward")
    return float(loss.detach().float().cpu()), {name: None if grad is None else grad.detach().cpu()
                                               for (name, _), grad in zip(named, gradients)}


def logical_rows(batch):
    sample_ids = batch["sample_ids"]
    spans = batch["reasoning_step_spans"]
    if len(sample_ids) != 1:
        raise ValueError("fixed probe requires exactly one real sample per rank")
    if spans and isinstance(spans[0], (tuple, list)):
        if len(spans) != 1:
            raise ValueError("source reasoning spans must have one sample group")
        spans = spans[0]
    rows = []
    for span in spans:
        rows.append([(sample_ids[0], int(span.step_id), position-1, int(batch["input_ids"][0, position]))
                     for position in range(span.target_text_start, span.target_text_end)])
    return rows


class ObjectiveObservation:
    """Observe only native reducer, selector, outer top-k and group-gap boundaries."""
    def __init__(self, trainer, variant, batch):
        self.trainer, self.variant = trainer, variant
        self.rows = logical_rows(batch)
        self.components, self.selections, self.support = [], [], []
        self.step_denominator = None
        self.phase = "forward"
        self.active_topk = None
        self.mapping_unresolved = []
        self.bound_chunks = {}
        self.stack = ExitStack()

    def __enter__(self):
        trainer_module = importlib.import_module("stage2.trainer")
        loss_module = importlib.import_module("step_preference.dil_topk_loss")
        selector = importlib.import_module("step_preference.entropy_selection")
        if self.variant != "portTorch":
            self.stack.enter_context(observe_call(self.trainer, "_reduce_step_preference_components", self._source_components))
            self.stack.enter_context(observe_call(trainer_module, "select_sample_entropy_masks", self._source_selection))
        else:
            self.stack.enter_context(observe_call(self.trainer, "_accumulate_step_preference_metrics", self._port_components))
            self.stack.enter_context(observe_call(selector, "select_entropy_masks", self._port_selection))
            chunk_module = importlib.import_module("transformers.models.qwen2_5_vl.stage2_shared_prefix")
            self.stack.enter_context(observe_call(chunk_module, "_score_chunk", self._bind_chunk))
        name = "topk_negative_and_mass" if self.variant != "portTorch" else "topk_token_terms"
        owner = trainer_module if self.variant != "portTorch" else loss_module
        original = getattr(owner, name)
        def topk(*args, **kwargs):
            context = self._topk_context(sys._getframe(1), args)
            previous = self.active_topk
            self.active_topk = {"context": context, "targets": args[2].detach().cpu().tolist(), "cursor": 0, "calls": 0}
            try:
                return original(*args, **kwargs)
            finally:
                self.active_topk = previous
        setattr(owner, name, topk)
        self.stack.callback(setattr, owner, name, original)
        self.stack.enter_context(observe_call(loss_module, "_group_gap", self._support))
        return self

    def __exit__(self, *exc):
        return self.stack.__exit__(*exc)

    def _source_components(self, args, kwargs, result):
        self.step_denominator = len(args[3])
        self.components.append({key: float(value.detach().float().cpu()) for key, value in result[1].items()})

    def _port_components(self, args, kwargs, result):
        self.step_denominator = int(args[0]["stats/eligible_steps"])
        self.components.append({key: float(value.detach().float().cpu()) if hasattr(value, "detach") else float(value)
                                for key, value in args[0].items()})

    def _source_selection(self, args, kwargs, result):
        self.selections.append({"inputs": {str(key): tensor_record(value) for key, value in args[1].items()},
                                "rows": [list(row) for item in args[0] for row, selected in zip(
                                    self.rows[item.span.step_id], result.masks[(item.sample_id, item.span.step_id)].cpu().tolist()) if selected],
                                "masks": {str(key): value.cpu().tolist() for key, value in result.masks.items()}})

    def _port_selection(self, args, kwargs, result):
        self.selections.append({"inputs": [tensor_record(value) for value in args[0]],
                                "rows": [list(row) for rows, mask in zip(self.rows, result) for row, selected in zip(rows, mask.cpu().tolist()) if selected],
                                "masks": [mask.cpu().tolist() for mask in result]})

    def _bind_chunk(self, args, kwargs, result):
        # The native factory binds the same target tensor in its score closure
        # for forward and checkpoint replay. Keep a reference to avoid ID reuse;
        # leave its returned function and tensor tuple completely unchanged.
        import inspect
        score = result[0]
        targets = inspect.getclosurevars(score).nonlocals.get("targets")
        rows = []
        for branch in args[1]:
            if branch.kind != "visual_off":
                return
            for local, target in zip(branch.selected_positions, branch.target_token_ids):
                rows.append([self.rows[branch.step_id][0][0], branch.step_id, branch.logical_positions[local], target])
        if targets is not None and [row[3] for row in rows] == targets.detach().cpu().tolist():
            self.bound_chunks[id(targets)] = (targets, rows)

    def _topk_context(self, frame, args):
        if self.variant != "portTorch":
            if frame.f_code.co_name == "_reduce_step_preference_components" and "item" in frame.f_locals:
                item = frame.f_locals["item"]
                rows = self.rows[item.span.step_id]
                selection = frame.f_locals.get("selection")
                if selection is not None:
                    rows = [row for row, selected in zip(rows, selection.masks[(item.sample_id, item.span.step_id)].cpu().tolist()) if selected]
                if [row[3] for row in rows] == args[2].detach().cpu().tolist():
                    return [list(row) for row in rows]
        else:
            bound = self.bound_chunks.get(id(args[2]))
            if bound is not None and bound[0] is args[2]:
                return bound[1]
        self.mapping_unresolved.append({"phase": self.phase, "reason": "native logical branch/chunk context unavailable"})
        return None

    def _support(self, args, kwargs, result):
        active = self.active_topk
        if active is None:
            raise ValueError("group gap without native outer top-k context")
        # Native clean then OFF calls share the same chosen support in each chunk.
        if active["calls"] % 2 == 0:
            mask = args[1].detach().cpu()
            start, stop = active["cursor"], active["cursor"]+mask.shape[0]
            identities = None if active["context"] is None else active["context"][start:stop]
            self.support.append({"phase": self.phase, "rows": identities, "targets": active["targets"][start:stop],
                                 "ids": [row.nonzero().flatten().tolist() for row in mask]})
            active["cursor"] = stop
        active["calls"] += 1

    def record(self):
        return {"components": self.components, "selections": self.selections, "support": self.support,
                "support_mapping_unresolved": self.mapping_unresolved, "original_step_denominator": self.step_denominator}


def native_dora_scope(model, variant, observation):
    if variant == "portTorch":
        observation.update(route="native port compute_loss", eligible=None, patched=None)
        return nullcontext()
    from stage2.dora import dora_microbatch_scope, _plain_linear
    from peft.tuners.lora.layer import Linear
    from peft.tuners.lora.dora import DoraLinearLayer
    eligible = []
    for layer in model.modules():
        if type(layer) is not Linear or layer.fan_in_fan_out or not _plain_linear(layer.get_base_layer()):
            continue
        for name, magnitude in layer.lora_magnitude_vector.items():
            a, b = layer.lora_A[name], layer.lora_B[name]
            if type(magnitude) is DoraLinearLayer and "forward" not in magnitude.__dict__ and _plain_linear(a) and _plain_linear(b) and a.bias is None and b.bias is None:
                eligible.append(magnitude)
    @contextmanager
    def scope():
        with dora_microbatch_scope(model, enabled=True):
            patched = sum("forward" in magnitude.__dict__ for magnitude in eligible)
            observation.update(route="source stage2.dora.dora_microbatch_scope", eligible=len(eligible), patched=patched)
            if not eligible or patched != len(eligible):
                raise ValueError("source DoRA scope did not patch every eligible module")
            yield
            if sum("forward" in magnitude.__dict__ for magnitude in eligible) != patched:
                raise ValueError("source DoRA scope changed before backward finished")
        observation["restored"] = all("forward" not in magnitude.__dict__ for magnitude in eligible)
    return scope()


def rotary_scope(repository, variant, observation):
    if variant != "sourceTorch":
        observation.update(variant=variant, controlled=False)
        return nullcontext()
    module = importlib.import_module("transformers.models.qwen2_5_vl.modeling_qwen2_5_vl")
    path = Path(repository)/MODEL_FILE
    parsed = ast.parse(path.read_text())
    helpers = [node for node in parsed.body if isinstance(node, ast.FunctionDef) and node.name in ("rotate_half", "apply_rotary_pos_emb_vision")]
    if len(helpers) != 2:
        raise ValueError("authenticated Torch rotary helpers missing")
    namespace = {"torch": importlib.import_module("torch"), "Tuple": tuple}
    exec(compile(ast.Module(body=helpers, type_ignores=[]), str(path), "exec"), namespace)
    replacement = namespace["apply_rotary_pos_emb_vision"]
    original = module.apply_rotary_pos_emb_flashatt
    import inspect
    replacement_text = ast.get_source_segment(path.read_text(), next(node for node in helpers if node.name == "apply_rotary_pos_emb_vision"))
    observation.update(controlled=True, helper_file_sha256=sha256(path), calls=0,
                       original_callable_sha256=hashlib.sha256(inspect.getsource(original).encode()).hexdigest(),
                       replacement_callable_sha256=hashlib.sha256(replacement_text.encode()).hexdigest())
    def controlled(*args, **kwargs):
        observation["calls"] += 1
        return replacement(*args, **kwargs)
    @contextmanager
    def scope():
        module.apply_rotary_pos_emb_flashatt = controlled
        try:
            yield
        finally:
            module.apply_rotary_pos_emb_flashatt = original
    return scope()


def validate_rank_records(records, run_id, manifest_sha256, variant):
    if len(records) != 4 or {record.get("rank") for record in records} != {0, 1, 2, 3}:
        raise ValueError("probe requires four actual global rank records")
    devices = set()
    for record in records:
        rank = record["rank"]
        if type(rank) is not int:
            raise ValueError("global rank must be an integer")
        expected = {"kind": "dil-full-model-probe-rank", "schema": SCHEMA, "run_id": run_id,
                    "manifest_sha256": manifest_sha256, "variant": variant, "world_size": 4,
                    "status": "complete", "machine_rank": rank//2, "local_rank": rank%2, "device": rank%2}
        if any(record.get(name) != value for name, value in expected.items()):
            raise ValueError("incompatible probe runtime/rank identity or worker error")
        cases = record.get("cases", [])
        if [case.get("raw_index") for case in cases] != [727, 2046] or any(case.get("repeats") != [0, 1] for case in cases):
            raise ValueError("incomplete diagnostic cases/repeats")
        state = record.get("bf16_cast_state")
        if (record.get("model_state_unchanged") is not True or record.get("deepspeed_engine_prepared") is not False
                or not record.get("loaded_state") or not isinstance(state, dict) or not state):
            raise ValueError("missing independently loaded model state or no-optimizer witness")
        trainable = {name: value for name, value in state.items() if value.get("trainable") is True}
        if not trainable:
            raise ValueError("missing trainable model state")
        for case in cases:
            observations = case.get("observations", [])
            if [observation.get("repeat") for observation in observations] != [0, 1]:
                raise ValueError("missing actual repeated differentiation")
            if not {"input_ids", "labels", "attention_mask", "pixel_values", "image_grid_thw"}.issubset(case.get("batch_tensors", {})):
                raise ValueError("missing actual multimodal collated input witness")
            for observation in observations:
                loss = observation.get("loss")
                gradients = observation.get("gradients", {})
                objective = observation.get("objective", {})
                if (type(loss) not in (int, float) or not math.isfinite(loss)
                        or set(gradients) != set(trainable) or not any(value is not None for value in gradients.values())
                        or len(objective.get("components", [])) != 1 or not objective.get("selections") or not objective.get("support")
                        or not re.fullmatch("[a-f0-9]{64}", observation.get("tensor_sha256", ""))):
                    raise ValueError("missing native objective/selection/support/all-parameter derivatives")
                for name, gradient in gradients.items():
                    if gradient is not None and (gradient.get("shape") != trainable[name]["shape"] or gradient.get("dtype") != trainable[name]["dtype"]):
                        raise ValueError("trainable parameter derivative shape/dtype mismatch")
        devices.add((record.get("host"), record["device"]))
    if len(devices) != 4:
        raise ValueError("four distinct actual host/devices not witnessed")
    return {"kind": "dil-full-model-probe", "schema": SCHEMA, "run_id": run_id,
            "manifest_sha256": manifest_sha256, "variant": variant, "world_size": 4,
            "arithmetic": "unscaled composed scalar autograd; no optimizer/ZeRO reduction", "ranks": sorted(records, key=lambda r: r["rank"])}


def publish_json(path, value):
    path = Path(path)
    path.parent.mkdir(parents=True, exist_ok=True)
    with path.open("x") as stream:
        stream.write(json_bytes(value).decode()+"\n")


