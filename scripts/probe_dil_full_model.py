def tree_hashes(root):
    """Authenticate complete Python runtime trees, excluding generated bytecode."""
    root = Path(root)
    files = sorted(set((root / "src").rglob("*.py")) | set((root / "transformers/src").rglob("*.py")))
    if not files:
        raise ValueError("empty runtime tree")
    return {str(path.relative_to(root)): sha256(path) for path in files}


def load_manifest(path, repository):
    manifest = read_json(path)
    required = {"schema", "variant", "data_path", "data_sha256", "image_root", "base", "initializer",
                "initializer_files", "base_files", "source_files", "port_files", "package_files", "cases", "profile", "comparator"}
    if set(manifest) != required or manifest["schema"] != SCHEMA or manifest["variant"] not in VARIANTS:
        raise ValueError("incompatible fixed probe manifest")
    if manifest["profile"] != PROFILE or manifest["comparator"] != COMPARATOR or manifest["cases"] != list(CASES):
        raise ValueError("fixed probe cases/profile/comparator differ")
    if manifest["base"] != BASE or Path(manifest["initializer"]).resolve() != (Path(repository)/"checkpoints"/INITIALIZER).resolve():
        raise ValueError("probe requires original base and original Stage1 initializer")
    contained(manifest["initializer"], Path(repository) / "checkpoints")
    contained(manifest["data_path"], Path(repository) / "data")
    contained(manifest["image_root"], Path(repository) / "data")
    for name in ("initializer_files", "base_files", "source_files", "port_files", "package_files"):
        hashes = manifest[name]
        if not isinstance(hashes, dict) or not hashes:
            raise ValueError(f"missing authenticated {name}")
        for relative, digest in hashes.items():
            if name != "package_files" and (Path(relative).is_absolute() or ".." in Path(relative).parts):
                raise ValueError("invalid identity path")
            if not isinstance(digest, str) or not re.fullmatch("[a-f0-9]{64}", digest):
                raise ValueError("invalid identity hash")
    return manifest


def authenticate(manifest, repository, machine_rank):
    root = Path(repository)
    source = SOURCE_REMOTE if machine_rank == 0 else SOURCE_LOCAL
    expected = manifest["port_files"] if manifest["variant"] == "portTorch" else manifest["source_files"]
    selected = root if manifest["variant"] == "portTorch" else source
    if tree_hashes(selected) != expected:
        raise ValueError("selected complete runtime tree changed")
    # The shared rotary helper must also be authenticated for sourceTorch.
    if sha256(root / MODEL_FILE) != manifest["port_files"].get(MODEL_FILE):
        raise ValueError("port rotary helper file changed")
    for directory, name in ((Path(manifest["initializer"]), "initializer_files"), (Path(manifest["base"]), "base_files")):
        actual_files = {str(p.relative_to(directory)): sha256(p) for p in directory.rglob("*") if p.is_file()}
        if actual_files != manifest[name]:
            raise ValueError(f"{name} bytes changed")
    for name, digest in manifest["package_files"].items():
        if sha256(name) != digest:
            raise ValueError(f"installed package changed: {name}")
    if sha256(manifest["data_path"]) != manifest["data_sha256"]:
        raise ValueError("TRAIN bytes changed")
    rows = Path(manifest["data_path"]).read_text().splitlines()
    for ordinal, case in enumerate(CASES):
        row = json.loads(rows[ordinal if len(rows) == 2 else case["raw_index"]])
        identity = row.get("sample_id") or hashlib.sha256(json.dumps(row, sort_keys=True, separators=(",", ":"), ensure_ascii=False).encode()).hexdigest()
        if identity != case["sample_id"]:
            raise ValueError("raw TRAIN case identity changed")
    return selected


def isolated_paths(selected, repository, paths):
    selected, repository = Path(selected), Path(repository)
    competitors = (repository, SOURCE_LOCAL, SOURCE_REMOTE)
    kept = []
    for value in paths:
        if not value:
            continue
        path = Path(value).absolute()
        # Preserve venv site-packages even when the venv lives below the repository.
        if "site-packages" in path.parts or "dist-packages" in path.parts:
            kept.append(value)
        elif not any(path == r or path.is_relative_to(r) for r in competitors):
            kept.append(value)
    return [str(selected / "transformers/src"), str(selected / "src"), str(selected), *kept]


def bootstrap(selected, repository):
    if any(name in sys.modules for name in ("torch", "transformers", "main", "stage2", "step_preference")):
        raise ValueError("runtime imported before isolated bootstrap")
    sys.path[:] = isolated_paths(selected, repository, sys.path)


